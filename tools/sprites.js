/**
 * Draw a sprite on a canvas context at (px, py) with given palette and scale.
 */
export function drawSprite(ctx, spriteName, px, py, palette, scale = 1) {
  const sprite = SPRITES[spriteName];
  if (!sprite) return;
  const size = scale;
  for (let row = 0; row < sprite.length; row++) {
    for (let col = 0; col < sprite[row].length; col++) {
      const ch = sprite[row][col];
      if (ch === '.') continue;
      const idx = parseInt(ch, 16);
      ctx.fillStyle = palette[idx] || '#ff00ff';
      ctx.fillRect(px + col * size, py + row * size, size, size);
    }
  }
}
